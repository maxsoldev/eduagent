"""The memory folder is a git repository, so phase 2 can see what changed since its last run.

Mirrors codex-rs/memories/write/src/workspace.rs and git-utils/src/baseline.rs (Codex uses the
`gix` library; we call the git command). After a successful phase 2 the folder becomes the new
one-commit baseline. Before the next run, phase 2 syncs its inputs and writes the git diff to
phase2_workspace_diff.md: added summaries mean new memories, deleted ones mean "forget this".
"""

import shutil
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

DIFF_FILENAME = "phase2_workspace_diff.md"
DIFF_MAX_BYTES = 4 * 1024 * 1024
GIT = ["git", "-c", "user.name=educodex", "-c", "user.email=educodex@localhost", "-c", "commit.gpgsign=false"]


@dataclass
class WorkspaceDiff:
    changes: list[tuple[str, str]] = field(default_factory=list)  # (A|M|D, path)
    unified_diff: str = ""


def _git(root: Path, *args: str) -> str:
    return subprocess.run([*GIT, "-C", str(root), *args], check=True, capture_output=True, text=True).stdout


def reset_baseline(root: Path) -> None:
    """A fresh repository with one commit, so deleted memories leave nothing behind in git."""
    (root / DIFF_FILENAME).unlink(missing_ok=True)
    shutil.rmtree(root / ".git", ignore_errors=True)
    _git(root, "init", "-q")
    _git(root, "add", "-A")
    _git(root, "commit", "-q", "--allow-empty", "-m", "memory baseline")


def prepare(root: Path) -> None:
    root.mkdir(parents=True, exist_ok=True)
    (root / DIFF_FILENAME).unlink(missing_ok=True)
    if not (root / ".git").is_dir():
        reset_baseline(root)


def diff(root: Path) -> WorkspaceDiff:
    (root / DIFF_FILENAME).unlink(missing_ok=True)
    _git(root, "add", "-A")
    status = _git(root, "diff", "--cached", "--no-renames", "--name-status")
    changes = [(line.split("\t", 1)[0], line.split("\t", 1)[1]) for line in status.splitlines() if "\t" in line]
    return WorkspaceDiff(changes, _git(root, "diff", "--cached", "--no-renames") if changes else "")


def write_diff_file(root: Path, workspace_diff: WorkspaceDiff) -> None:
    text = (
        "# Memory Workspace Diff\n\n"
        "Generated by Codex before Phase 2 memory consolidation. Read this file first and do not edit it.\n\n"
        "## Status\n"
    )
    if not workspace_diff.changes:
        text += "- none\n"
    else:
        text += "".join(f"- {status} {path}\n" for status, path in workspace_diff.changes)
        unified = workspace_diff.unified_diff
        if len(unified.encode()) > DIFF_MAX_BYTES:
            unified = unified.encode()[:DIFF_MAX_BYTES].decode(errors="ignore")
            unified += f"\n[workspace diff truncated at {DIFF_MAX_BYTES} bytes]\n"
        text += "\n## Diff\n\n```diff\n" + unified + ("" if unified.endswith("\n") else "\n") + "```\n"
    (root / DIFF_FILENAME).write_text(text)


def remove_symlinks(root: Path) -> int:
    """The memory agent must not leave links to files outside the folder."""
    links = [p for p in root.rglob("*") if p.is_symlink() and ".git" not in p.relative_to(root).parts]
    for link in links:
        link.unlink()
    return len(links)


def validate_artifacts(root: Path) -> str | None:
    """None if phase 2 left a valid MEMORY.md and memory_summary.md, else the problem."""
    if removed := remove_symlinks(root):
        return f"removed {removed} symbolic links from consolidated memory workspace"
    if not (root / "MEMORY.md").is_file():
        return "MEMORY.md is missing"
    summary = root / "memory_summary.md"
    if not summary.is_file() or summary.read_text().split("\n", 1)[0] != "v1":
        return "memory_summary.md is missing or does not start with v1"
    return None
